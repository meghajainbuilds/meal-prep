import { db } from '../db.mjs'

export default async function generateWeek() {
  const monday = nextMonday()
  const weekStart = monday.toISOString().slice(0, 10)

  const { data: existing } = await db
    .from('weeks')
    .select('id, version')
    .eq('week_start', weekStart)
    .order('version', { ascending: false })
    .limit(1)
    .maybeSingle()

  if (existing) {
    return { skipped: true, reason: `Week ${weekStart} already exists at v${existing.version}` }
  }

  const { data, error } = await db
    .from('weeks')
    .insert({
      week_start: weekStart,
      version: 1,
      notes: 'Draft generated by Friday scheduled job. Full meal-plan generation lands with the planner UI.',
    })
    .select('id, week_start, version')
    .single()
  if (error) throw error
  return { created: data }
}

function nextMonday() {
  const now = new Date()
  const dow = now.getUTCDay()
  const daysUntilMon = (8 - dow) % 7 || 7
  const next = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate() + daysUntilMon))
  return next
}
